"""python -m contracts.generate [--check]; no database access or routed schema."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
import django

django.setup()
from django.urls import URLResolver, get_resolver
from .schema import build, VERSION

ROOT = Path(__file__).resolve().parents[3]
PACKAGE = ROOT / "packages/api-contracts"


def encoded(value):
    return json.dumps(value, indent=2, sort_keys=True) + "\n"


def routes(patterns=None, prefix=""):
    result = set()
    for entry in patterns if patterns is not None else get_resolver().url_patterns:
        path = prefix + str(entry.pattern)
        if isinstance(entry, URLResolver):
            result.update(routes(entry.url_patterns, path))
        else:
            result.add("/" + re.sub(r"<[^:>]+:([^>]+)>", r"{\1}", path))
    return result


def source_lock():
    paths = [ROOT / "apps/backend/config/urls.py", ROOT / "apps/backend/config/settings.py"]
    for folder in ("accounts", "access", "organizations"):
        paths.extend(p for p in (ROOT / "apps/backend" / folder).glob("*.py")
                     if not p.name.startswith("test") and p.name not in ("admin.py", "apps.py"))
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)}


def fingerprint(value):
    return hashlib.sha256(encoded(value).encode()).hexdigest()


def compatibility(document):
    return {"version": VERSION, "operations": {path + " " + method: fingerprint(op)
            for path, methods in document["paths"].items() for method, op in methods.items()},
            "schemas": {name: fingerprint(schema) for name, schema in document["components"]["schemas"].items()},
            "security": fingerprint(document["components"]["securitySchemes"]),
            "global_security": fingerprint(document["x-pwc-security"]),
            "protocol": fingerprint({key: document[key] for key in ("servers", "openapi")})}


def browser_catalog(document):
    selected = {"csrf", "me", "mfaStatus", "logout", "stepUp", "clearHold"}
    catalog = {}
    for path, methods in document["paths"].items():
        for method, op in methods.items():
            if op["operationId"] in selected:
                catalog[op["operationId"]] = {"path": path.removeprefix("/api/v1/auth/"), "method": method.upper(),
                    "transport": "same-origin-cookie", "csrf": op["x-pwc"]["csrf"], "availability": op["x-pwc"]["availability"]}
    assert set(catalog) == selected
    return "// Generated by contracts.generate; no transport or credentials.\nexport const contractVersion = " + json.dumps(VERSION) + " as const;\nexport const browserOperations = " + json.dumps(catalog, indent=2, sort_keys=True) + " as const;\n"


def check_compatibility(before, after):
    for section in ("operations", "schemas"):
        for key, value in before[section].items():
            assert after[section].get(key) == value, "Frozen v1 compatibility changed; human version review required: " + key
    for section in ("security", "global_security", "protocol"):
        assert before[section] == after[section], "Security/protocol compatibility changed: " + section


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = build()
    assert routes() == set(document["paths"]), "Django route inventory drift: review annotations"
    outputs = {PACKAGE / "openapi-v1.json": encoded(document), PACKAGE / "source-lock.json": encoded(source_lock()),
               PACKAGE / "generated/browser-operations.ts": browser_catalog(document)}
    # Reject incompatible output BEFORE touching any checked artifact.
    check_compatibility(json.loads((PACKAGE / "compatibility-v1.json").read_text()), compatibility(document))
    for path, text in outputs.items():
        if args.check:
            assert path.exists() and path.read_text() == text, "Generated contract drift: " + str(path.relative_to(ROOT))
        else:
            path.write_text(text)
    print("Contract generation/inventory/source/compatibility checks passed")


if __name__ == "__main__":
    main()
