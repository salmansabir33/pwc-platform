"""Generate/check fixed REDACTED P4 demonstration assets, never a live API schema."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/backend"))


def main():
    from organizations.membership_demonstrations import demonstrations

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    content = (
        json.dumps(demonstrations(), ensure_ascii=False, indent=2, sort_keys=True)
        + "\n"
    )
    outputs = {
        ROOT
        / "packages/api-contracts/fixtures/membership-demonstrations.json": content,
        ROOT
        / "apps/mobile/lib/core/membership_demonstrations.g.dart": "// Generated by scripts/membership_demonstrations.py; fixed fictional counts/codes only.\n"
        "const membershipDemonstrationsJson = r'''\n" + content + "''';\n",
    }
    for path, expected in outputs.items():
        if options.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(
                    "Membership demonstration drift: " + str(path.relative_to(ROOT))
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    print(
        "Fixed redacted membership demonstration parity checked"
        if options.check
        else "Fixed membership demonstrations generated"
    )


if __name__ == "__main__":
    main()
