"""Small deterministic adapters; manifest meanings shared, never React widgets."""
import json
from pathlib import Path
import re
import sys
root=Path(__file__).resolve().parent.parent
manifest=json.loads((root/'packages/design-tokens/tokens.v1.json').read_text())
def kebab(name):return re.sub(r'([A-Z])',r'-\1',name).lower()
css=['/* Generated by scripts/design_tokens.py; edit tokens.v1.json. */',':root {','  --design-version: "'+manifest['version']+'";']
for k,v in manifest['colors'].items():css.append(f'  --ds-{kebab(k)}: {v.lower()};')
for key,prefix in [('spacing','space'),('radii','radius'),('typeSizes','type')]:
 for n in manifest[key]:css.append(f'  --ds-{prefix}-{n}: {n/16:g}rem;')
for key in ('controlHeight','webTarget','borderWidth','focusWidth','focusOffset'):css.append(f'  --ds-{kebab(key)}: {manifest[key]}px;')
css+=['}','']
dart=["// Generated by scripts/design_tokens.py; edit tokens.v1.json.","import 'package:flutter/material.dart';",'abstract final class PwcTokens {',f"  static const version = '{manifest['version']}';"]
for k,v in manifest['colors'].items():dart.append(f'  static const {k} = Color(0xff{v[1:].lower()});')
for key in ('spacing','radii','typeSizes','lineHeights','breakpoints'):
 dart.append(f"  static const {key} = <double>[{', '.join(str(n)+'.0' for n in manifest[key])}];")
for key in ('controlHeight','webTarget','mobileTarget','borderWidth','focusWidth','focusOffset'):dart.append(f'  static const {key} = {manifest[key]}.0;')
for k,v in manifest['fonts'].items():dart.append(f"  static const {k}Font = '{v}';")
dart+=['}','']
outputs={'packages/design-tokens/generated.css':'\n'.join(css),'apps/mobile/lib/design/tokens.g.dart':'\n'.join(dart)}
for p,text in outputs.items():
 file=root/p
 if '--check' in sys.argv:
  def normalized(value):
   return re.sub(r"'[^']*'|\s+", lambda m: m[0] if m[0].startswith("'") else '', value) if p.endswith('.dart') else value
  if normalized(file.read_text())!=normalized(text):raise SystemExit('Design token drift: '+p)
 else:file.write_text(text)
print('Design token adapters checked' if '--check' in sys.argv else 'Design token adapters generated')
