"""Deterministic bounded Dart models and personal operation manifest from PWC-03C.

No endpoint or schema edits; --check detects drift. The source digest is a
provenance binding, not authorization. Never generate NGO synthetic operations.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import subprocess
import tempfile
import shutil

root = Path(__file__).resolve().parent.parent
source = root / 'packages/api-contracts/openapi-v1.json'
spec = json.loads(source.read_text())
schemas = spec['components']['schemas']
consumed = set()
ops = []
for path, methods in spec['paths'].items():
    if not path.startswith('/api/v1/auth/') or '/web/' in path or path.endswith('/csrf/'):
        continue
    for method, op in methods.items():
        def ref(content):
            return content.get('application/json', {}).get('schema', {}).get('$ref', '').split('/')[-1]
        request = ref(op.get('requestBody', {}).get('content', {}))
        response = {code: ref(value.get('content', {})) for code, value in op['responses'].items() if code.startswith('2')}
        consumed.update([request, *response.values()])
        public = '/mobile/' in path or '/registration/' in path or '/password-reset/' in path
        ops.append({'id': op['operationId'], 'path': path, 'method': method.upper(), 'request': request, 'responses': response, 'authenticated': not public})
consumed.discard('')
selected = {k: v for k,v in schemas.items() if k in consumed}
# Inline nested DTOs with deterministic names, keeping canonical top-level schema.
models = {}
def pascal(s):
    return ''.join(part[:1].upper()+part[1:] for part in s.split('_'))
def camel(s):
    p=pascal(s)
    return p[:1].lower()+p[1:]
def kind(s, name):
    if '$ref' in s:
        return s['$ref'].split('/')[-1]
    if s.get('type') == 'object':
        models[name] = s
        return name
    if s.get('type') == 'array':
        return 'List<'+kind(s['items'],name+'Item')+'>'
    if 'anyOf' in s:
        return kind(next(x for x in s['anyOf'] if x.get('type')!='null'),name)+'?'
    return {'string':'String','integer':'int','boolean':'bool','number':'num'}.get(s.get('type'),'Object?')
for name,schema in selected.items():
    if schema.get('type')=='object': models[name]=schema
fields={}
pending=list(models)
while pending:
    name=pending.pop(0)
    s=models[name]
    fields[name]=[(prop,kind(value,name+pascal(prop))) for prop,value in s['properties'].items()]
    pending.extend(k for k in models if k not in fields and k not in pending)

def expr(typ, field):
    if typ.endswith('?'): return f'{field} == null ? null : '+expr(typ[:-1],field)
    if typ.startswith('List<'):
        return f'({field} as List).map((v) => {expr(typ[5:-1],"v")}).toList(growable: false)'
    if typ in ('String','int','bool','num','Object'):return f'{field} as {typ}'
    return f'{typ}.fromJson(Map<String, Object?>.from({field} as Map))'
lines=['// Generated by scripts/mobile_contracts.py; do not edit.', "import 'dart:convert';", "import 'contract_validation.dart';",'typedef Json = Map<String, Object?>;',f"const contractSha256 = '{hashlib.sha256(source.read_bytes()).hexdigest()}';", "final Map<String, dynamic> canonicalSchemas = jsonDecode(r'''"+json.dumps(selected,ensure_ascii=False,separators=(',',':'))+"''') as Map<String, dynamic>;", "final List<dynamic> personalOperations = jsonDecode(r'''"+json.dumps(ops,separators=(',',':'))+"''') as List<dynamic>;"]
for name,s in models.items():
    lines += [f'class {name} {{', '  final Json _data;', f"  {name}.fromJson(Json data) : _data = checkedObject(data, {json.dumps(s,separators=(',',':')) if False else 'schema'+name}, canonicalSchemas);",f'  Json toJson() => Map<String, Object?>.from(jsonDecode(jsonEncode(_data)) as Map);', '  @override', f"  String toString() => '{name}(<redacted>)';"]
    for prop,typ in fields[name]:
        optional=prop not in s.get('required',[])
        if optional and not typ.endswith('?'):typ+='?'
        lines.append(f"  {typ} get {camel(prop)} => {expr(typ, '_data['+repr(prop)+']')};")
    lines.append('}')
    lines.append("final Map<String, dynamic> schema"+name+" = jsonDecode(r'''"+json.dumps(s,separators=(',',':'))+"''') as Map<String, dynamic>;")
# Schema-based operation validation also supports union requests.
text='\n'.join(lines)+'\n'
target=root/'apps/mobile/lib/core/contracts.g.dart'
if '--check' in sys.argv:
    if not shutil.which('dart'): raise SystemExit('Contract drift check requires pinned Dart formatter')
    with tempfile.TemporaryDirectory(dir=target.parent) as temporary:
        expected=Path(temporary)/'contracts.g.dart'
        expected.write_text(text)
        subprocess.run(['dart','format',str(expected)],check=True,stdout=subprocess.DEVNULL)
        if target.read_text()!=expected.read_text(): raise SystemExit('Mobile contract generation drift')
else:
    target.write_text(text)
    if shutil.which('dart'):subprocess.run(['dart','format',str(target)],check=True)
print(f'{len(models)} typed models; {len(ops)} personal operations; source SHA256 bound')
