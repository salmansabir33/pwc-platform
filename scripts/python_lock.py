"""Generate hash locks from exact sources and PyPI HTTPS release metadata.

Run from root: python -m scripts.python_lock [--check]. Check is offline;
installation with pip --require-hashes verifies the actual downloaded bytes.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import re
import urllib.request

from scripts.python_dependency_review import FILES, ROOT, pins

LOCKS = {
    "apps/backend/requirements.lock": FILES[:1],
    "requirements-ci.lock": FILES,
}


def specifications(files):
    text = "\n".join((ROOT / name).read_text() for name in files)
    packages = pins(text)
    extras = {}
    for line in text.splitlines():
        match = re.match(r"([\w.-]+)\[([\w,.-]+)\]==", line)
        if match:
            name = re.sub(r"[-_.]+", "-", match[1]).lower()
            extras.setdefault(name, set()).update(match[2].split(","))
    return {
        name
        + (
            "[" + ",".join(sorted(extras[name])) + "]" if name in extras else ""
        ): version
        for name, version in sorted(packages.items())
    }


def release_hashes(item):
    name, version = item
    base = name.split("[")[0]
    with urllib.request.urlopen(
        f"https://pypi.org/pypi/{base}/{version}/json", timeout=30
    ) as response:
        data = json.load(response)
    hashes = sorted(
        {
            entry["digests"]["sha256"]
            for entry in data["urls"]
            if not entry.get("yanked")
        }
    )
    if not hashes or any(not re.fullmatch(r"[0-9a-f]{64}", value) for value in hashes):
        raise ValueError("Missing/invalid release hashes")
    return name, hashes


def check_lock(path, specs):
    headers = {}
    hashes = 0
    for line in Path(path).read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        if line.startswith("    --hash=sha256:"):
            if not re.fullmatch(r"    --hash=sha256:[0-9a-f]{64}(?: \\)?", line):
                raise ValueError("Invalid lock hash")
            hashes += 1
        else:
            if headers and not hashes:
                raise ValueError("Missing lock hashes")
            match = re.fullmatch(
                r"([\w.,\[\]-]+)==([\w.+-]+)", line.removesuffix(" " + chr(92))
            )
            if not match or match[1] in headers:
                raise ValueError("Invalid lock entry")
            headers[match[1]] = match[2]
            hashes = 0
    if headers != specs or not hashes:
        raise ValueError("Lock/source drift")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for target, files in LOCKS.items():
        specs = specifications(files)
        path = ROOT / target
        if args.check:
            check_lock(path, specs)
        else:
            with ThreadPoolExecutor(max_workers=6) as pool:
                hashes = dict(pool.map(release_hashes, specs.items()))
            lines = [
                "# Generated by python -m scripts.python_lock; never hand-edit hashes."
            ]
            for name, version in specs.items():
                lines.append(f"{name}=={version} \\")
                values = hashes[name]
                lines.extend(
                    "    --hash=sha256:"
                    + value
                    + (" \\" if i < len(values) - 1 else "")
                    for i, value in enumerate(values)
                )
            path.write_text("\n".join(lines) + "\n")
            check_lock(path, specs)
        print(f"Python hash lock checked: {target} ({len(specs)} versions)")


if __name__ == "__main__":
    main()
